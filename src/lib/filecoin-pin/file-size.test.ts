// @vitest-environment node
import { CID } from 'multiformats/cid'
import { sha256 } from 'multiformats/hashes/sha2'
import { afterEach, expect, it, vi } from 'vitest'
import type { DatasetPiece } from '../../hooks/use-dataset-pieces.ts'
import { recoverFileSize, recoverMissingFileSizes } from './file-size.ts'

const signal = () => new AbortController().signal
const record = (cid: string): DatasetPiece =>
  ({ id: cid, cid, serviceURL: 'https://sp.example', fileSize: 'Unknown', datasetId: '1' }) as DatasetPiece
const raw = (bytes: Uint8Array) =>
  new Response(new Uint8Array(bytes), { headers: { 'content-type': 'application/vnd.ipld.raw' } })
afterEach(() => vi.unstubAllGlobals())
it('recovers a raw file size, validates its CID and uses a second provider when needed', async () => {
  const bytes = new TextEncoder().encode('hello')
  const cid = CID.createV1(0x55, await sha256.digest(bytes)).toString()
  const fetcher = vi
    .fn()
    .mockResolvedValueOnce(new Response('', { status: 503 }))
    .mockResolvedValueOnce(raw(bytes))
  vi.stubGlobal('fetch', fetcher)
  const file = { ...record(cid), serviceURLs: ['https://first.example', 'https://second.example'] }
  expect(await recoverFileSize(file, signal())).toBe('5 Bytes')
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(String(fetcher.mock.calls[1][0])).toBe(`https://second.example/ipfs/${cid}?format=raw`)
})
it('reads the root block of a multi-block UnixFS file without fetching children', async () => {
  // Root generated by filecoin-pin's browser packer for a 3 MiB zero-filled file.
  const cid = 'bafybeigdsjup7aizxrrjn7yqtcmqg6ffksaugwr7is2ind3cf7esaqrz4m'
  const bytes = new Uint8Array(
    Buffer.from(
      '122c0a240155122030e14955ebf1352266dc2ff8067e68104607e750abb9d3b36582b8af909fcb58120018808040122c0a240155122030e14955ebf1352266dc2ff8067e68104607e750abb9d3b36582b8af909fcb58120018808040122c0a240155122030e14955ebf1352266dc2ff8067e68104607e750abb9d3b36582b8af909fcb581200188080400a130802188080c001208080402080804020808040',
      'hex'
    )
  )
  const fetcher = vi.fn().mockResolvedValue(raw(bytes))
  vi.stubGlobal('fetch', fetcher)
  expect(await recoverFileSize(record(cid), signal())).toBe('3 MB')
  expect(fetcher).toHaveBeenCalledOnce()
})
it('refuses a wrong block or a CAR response instead of displaying an incorrect size', async () => {
  const cid = CID.createV1(0x55, await sha256.digest(new TextEncoder().encode('correct'))).toString()
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(raw(new TextEncoder().encode('wrong'))))
  await expect(recoverFileSize(record(cid), signal())).rejects.toThrow('unavailable')
  const cancel = vi.fn()
  vi.stubGlobal(
    'fetch',
    vi
      .fn()
      .mockResolvedValue(
        new Response(new ReadableStream({ cancel }), { headers: { 'content-type': 'application/vnd.ipld.car' } })
      )
  )
  await expect(recoverFileSize(record(cid), signal())).rejects.toThrow('unavailable')
  expect(cancel).toHaveBeenCalledOnce()
})
it('cancels oversized reads and keeps optional enrichment failures nonfatal', async () => {
  const cid = CID.createV1(0x55, await sha256.digest(new Uint8Array([1]))).toString()
  const cancel = vi.fn()
  vi.stubGlobal(
    'fetch',
    vi.fn().mockImplementation(
      async () =>
        new Response(
          new ReadableStream({
            start(controller) {
              controller.enqueue(new Uint8Array(2 * 1024 * 1024 + 1))
            },
            cancel,
          }),
          { headers: { 'content-type': 'application/vnd.ipld.raw' } }
        )
    )
  )
  const save = vi.fn()
  await recoverMissingFileSizes([record(cid)], signal(), save)
  expect(cancel).toHaveBeenCalledOnce()
  expect(save).not.toHaveBeenCalled()
})
it('deduplicates content and skips cached sizes, archives and deleted records', async () => {
  const bytes = new Uint8Array([1])
  const cid = CID.createV1(0x55, await sha256.digest(bytes)).toString()
  const fetcher = vi.fn().mockImplementation(async () => raw(bytes))
  vi.stubGlobal('fetch', fetcher)
  const save = vi.fn()
  await recoverMissingFileSizes(
    [
      record(cid),
      record(cid),
      { ...record(cid), fileSize: '1 Byte' },
      { ...record(cid), importedCar: true },
      { ...record(cid), removedCopies: ['1'] },
    ],
    signal(),
    save
  )
  expect(fetcher).toHaveBeenCalledOnce()
  expect(save).toHaveBeenCalledWith(expect.objectContaining({ cid }), '1 Bytes')
})

it('limits size requests to two and stops saving or starting jobs after abort', async () => {
  const records = await Promise.all(
    [1, 2, 3].map(async (value) => record(CID.createV1(0x55, await sha256.digest(new Uint8Array([value]))).toString()))
  )
  const releases: Array<() => void> = []
  const fetcher = vi.fn(
    () =>
      new Promise<Response>((resolve) => {
        releases.push(() => resolve(raw(new Uint8Array([1]))))
      })
  )
  vi.stubGlobal('fetch', fetcher)
  const controller = new AbortController()
  const save = vi.fn()
  const work = recoverMissingFileSizes(records, controller.signal, save)
  expect(fetcher).toHaveBeenCalledTimes(2)
  controller.abort()
  for (const release of releases) release()
  await work
  expect(fetcher).toHaveBeenCalledTimes(2)
  expect(save).not.toHaveBeenCalled()
})
